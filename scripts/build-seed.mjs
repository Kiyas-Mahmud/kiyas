// Writes migrations/0002_seed.sql from worker/seed.json.
// INSERT OR IGNORE: never overwrites content already edited in the admin.
import { readFileSync, writeFileSync } from "node:fs";
const seed = JSON.parse(readFileSync(new URL("../worker/seed.json", import.meta.url)));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const now = Date.now();
const lines = Object.entries(seed).map(
  ([key, data]) => `INSERT OR IGNORE INTO sections (key, data, updated_at) VALUES (${q(key)}, ${q(JSON.stringify(data))}, ${now});`
);
writeFileSync(new URL("../migrations/0002_seed.sql", import.meta.url), `-- Generated by scripts/build-seed.mjs\n${lines.join("\n")}\n`);
console.log(`seeded ${lines.length} sections`);
